"""Section 4.1: the server as a permanent service of the user, on any system.

- Linux: a ``systemd --user`` unit, with ``loginctl enable-linger`` so it runs
  without an open session and comes back after a reboot.
- macOS: a ``launchd`` agent.
- Windows: a scheduled task at logon, in the user's session (idle detection
  needs it), with no execution time limit and restart on failure.

Every one of them runs ``<home>/server_launcher.py``, which knows where the
code and the home are and sends the server's output to ``<home>/server.log``.
"""

from __future__ import annotations

import getpass
import os
import subprocess
import sys
from dataclasses import dataclass, field
from typing import Dict, List
from xml.sax.saxutils import escape

PACKAGE_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LAUNCHER = '''"""Started by the fila service. Generated by fila."""
import os
import sys

HOME = {home!r}
sys.path.insert(0, {package_root!r})
os.environ["FILA_HOME"] = HOME
log = open(os.path.join(HOME, {log!r}), "a", buffering=1, encoding="utf-8")
sys.stdout = sys.stderr = log

from fila.cli import main

sys.exit(main({args!r} + sys.argv[1:], home=HOME))
'''

# The command a pull node's restricted key forces: stdout is the channel, so no log redirection.
CLI_LAUNCHER = '''"""Runs fila for the coordinator's home. Generated by fila."""
import os
import sys

HOME = {home!r}
sys.path.insert(0, {package_root!r})
os.environ["FILA_HOME"] = HOME

from fila.cli import main

sys.exit(main(sys.argv[1:], home=HOME))
'''


def write_cli_launcher(home: str) -> str:
    path = os.path.join(home, "fila_launcher.py")
    os.makedirs(home, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(CLI_LAUNCHER.format(home=home, package_root=PACKAGE_ROOT))
    return path


@dataclass
class ServicePlan:
    files: Dict[str, str] = field(default_factory=dict)  # path -> content
    commands: List[List[str]] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)


def system() -> str:
    return {"win32": "windows", "darwin": "macos"}.get(sys.platform, "linux")


def install_plan(home: str, name: str = "fila-server", system_name: str = None, python: str = None,
                 args: List[str] = ("server",), log: str = "server.log", launcher_name: str = "server_launcher.py",
                 package_root: str = PACKAGE_ROOT, description: str = "fila coordinator") -> ServicePlan:
    """The server's service; with ``args=["worker", "run", ...]`` a pull node's worker."""
    system_name = system_name or system()
    python = python or _service_python(system_name)
    launcher = os.path.join(home, launcher_name)
    plan = ServicePlan(files={launcher: LAUNCHER.format(home=home, package_root=package_root, log=log, args=list(args))})
    if system_name == "linux":
        unit = os.path.expanduser(f"~/.config/systemd/user/{name}.service")
        plan.files[unit] = (
            f"[Unit]\nDescription={description}\nAfter=network-online.target\n\n"
            f"[Service]\nExecStart={python} {launcher}\nRestart=on-failure\nRestartSec=10\n\n"
            "[Install]\nWantedBy=default.target\n"
        )
        plan.commands = [
            ["systemctl", "--user", "daemon-reload"],
            ["systemctl", "--user", "enable", "--now", f"{name}.service"],
            ["loginctl", "enable-linger", getpass.getuser()],
        ]
    elif system_name == "macos":
        agent = os.path.expanduser(f"~/Library/LaunchAgents/org.fila.{name}.plist")
        plan.files[agent] = _plist(name, python, launcher, home)
        plan.commands = [["launchctl", "load", "-w", agent]]
    else:
        task = os.path.join(home, f"{name}.xml")
        plan.files[task] = _task_xml(python, launcher, description)
        plan.commands = [
            ["schtasks", "/Create", "/TN", name, "/XML", task, "/F"],
            ["schtasks", "/Run", "/TN", name],
        ]
        plan.notes.append("The task starts at logon: if Windows restarts, the server returns when you sign in.")
    return plan


def uninstall_plan(home: str, name: str = "fila-server", system_name: str = None) -> ServicePlan:
    system_name = system_name or system()
    plan = ServicePlan()
    if system_name == "linux":
        plan.commands = [["systemctl", "--user", "disable", "--now", f"{name}.service"]]
        plan.notes.append(f"Remove ~/.config/systemd/user/{name}.service if you no longer want it.")
    elif system_name == "macos":
        plan.commands = [["launchctl", "unload", "-w", os.path.expanduser(f"~/Library/LaunchAgents/org.fila.{name}.plist")]]
    else:
        plan.commands = [["schtasks", "/End", "/TN", name], ["schtasks", "/Delete", "/TN", name, "/F"]]
    return plan


def execute(plan: ServicePlan) -> List[str]:
    """Write the files and run the commands; returns problems, empty if none."""
    problems = []
    for path, content in plan.files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        encoding = "utf-16" if path.endswith(".xml") else "utf-8"  # schtasks reads UTF-16 XML
        with open(path, "w", encoding=encoding, newline="\n") as handle:
            handle.write(content)
    for command in plan.commands:
        try:
            result = subprocess.run(command, capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.TimeoutExpired) as error:
            problems.append(f"{' '.join(command)}: {error}")
            continue
        if result.returncode != 0:
            problems.append(f"{' '.join(command)}: {(result.stderr or result.stdout).strip()}")
    return problems


def _service_python(system_name: str) -> str:
    """On Windows, pythonw.exe: the same interpreter without a console window."""
    if system_name == "windows":
        windowless = os.path.join(os.path.dirname(sys.executable), "pythonw.exe")
        if os.path.exists(windowless):
            return windowless
    return sys.executable


def _plist(name: str, python: str, launcher: str, home: str) -> str:
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>org.fila.{escape(name)}</string>
  <key>ProgramArguments</key>
  <array><string>{escape(python)}</string><string>{escape(launcher)}</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>StandardErrorPath</key><string>{escape(os.path.join(home, "server.log"))}</string>
</dict>
</plist>
"""


def _task_xml(python: str, launcher: str, description: str = "fila coordinator") -> str:
    user = escape(f"{os.environ.get('USERDOMAIN', '')}\\{getpass.getuser()}".lstrip("\\"))
    return f"""<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>{escape(description)}</Description></RegistrationInfo>
  <Triggers>
    <LogonTrigger><Enabled>true</Enabled><UserId>{user}</UserId></LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>{user}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>
    <Enabled>true</Enabled>
  </Settings>
  <Actions Context="Author">
    <Exec><Command>{escape(python)}</Command><Arguments>"{escape(launcher)}"</Arguments></Exec>
  </Actions>
</Task>
"""
